func foldConfusables(text string) string {
	result := make([]rune, 0, len(text))
	changed := false
	for _, r := range text {
		if rep, ok := confusables[r]; ok {
			result = append(result, rep)
			changed = true
		} else {
			result = append(result, r)
		}
	}
	if !changed {
		return text
	}
	return string(result)
}
